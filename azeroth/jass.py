"""Generates war3map.j in the same shape the World Editor produces for a map without triggers."""
import math

from .terrain import LEFT, BOTTOM, MAP_W, MAP_H, MARGIN_L, MARGIN_R, MARGIN_B, MARGIN_T

RACE_PREF = {'human': 'RACE_PREF_HUMAN', 'orc': 'RACE_PREF_ORC', 'undead': 'RACE_PREF_UNDEAD',
             'nightelf': 'RACE_PREF_NIGHTELF', 'random': 'RACE_PREF_RANDOM'}
CHUNK = 150   # units per creation function, keeps each function small


def playable_bounds():
    return (LEFT + MARGIN_L * 128.0, BOTTOM + MARGIN_B * 128.0,
            LEFT + (MAP_W - MARGIN_R) * 128.0, BOTTOM + (MAP_H - MARGIN_T) * 128.0)


def r(v):
    return ('%.1f' % v)


def jstr(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def rect_var(region):
    return 'gg_rct_' + ''.join(c if c.isalnum() else '_' for c in region['name'])


def generate(info, objects):
    regions = objects.regions
    units = objects.units
    starts = sorted(objects.starts)
    L = []
    w = L.append
    w('globals')
    w('    // Generated')
    for reg in regions:
        w('rect %s= null' % rect_var(reg))
    w('endglobals')
    w('')
    w('//===========================================================================')
    w('// ')
    w('// %s' % info['name'])
    w('// ')
    w('//   Warcraft III map script')
    w('//   Generated by the Azeroth map generator')
    w('//   Map Author: %s' % info['author'])
    w('// ')
    w('//===========================================================================')
    w('')
    w('function InitGlobals takes nothing returns nothing')
    w('endfunction')
    w('')

    def creation_functions(prefix, owner, selected, body):
        names = []
        for c in range(0, max(len(selected), 1), CHUNK):
            name = '%s_%d' % (prefix, c // CHUNK + 1)
            names.append(name)
            w('function %s takes nothing returns nothing' % name)
            w('    local player p= Player(%s)' % owner)
            w('    local unit u')
            w('    local trigger t')
            w('')
            for u in selected[c:c + CHUNK]:
                body(u)
            w('endfunction')
            w('')
        return names

    region_by_index = {reg['index']: reg for reg in regions}

    def passive_building(u):
        w("    set u=CreateUnit(p, '%s', %s, %s, %.3f)" % (u['id'], r(u['x']), r(u['y']), u['angle']))
        if u.get('waygate', -1) >= 0:
            rv = rect_var(region_by_index[u['waygate']])
            w('    call WaygateSetDestination(u, GetRectCenterX(%s), GetRectCenterY(%s))' % (rv, rv))
            w('    call WaygateActivate(u, true)')

    def passive(u):
        w("    set u=CreateUnit(p, '%s', %s, %s, %.3f)" % (u['id'], r(u['x']), r(u['y']), u['angle']))

    buildings = [u for u in units if u['kind'] == 'waygate']
    critters = [u for u in units if u['kind'] == 'critter']
    f_build = creation_functions('CreateNeutralPassiveBuildings', 'PLAYER_NEUTRAL_PASSIVE', buildings, passive_building)
    f_pass = creation_functions('CreateNeutralPassive', 'PLAYER_NEUTRAL_PASSIVE', critters, passive)

    w('function CreateAllUnits takes nothing returns nothing')
    for name in f_build + f_pass:
        w('    call %s()' % name)
    w('endfunction')
    w('')
    w('function CreateRegions takes nothing returns nothing')
    w('    local weathereffect we')
    w('')
    for reg in regions:
        w('    set %s=Rect(%s, %s, %s, %s)' % (rect_var(reg), r(reg['left']), r(reg['bottom']), r(reg['right']), r(reg['top'])))
    w('endfunction')
    w('')
    w('//===========================================================================')
    w('function InitCustomTriggers takes nothing returns nothing')
    w('endfunction')
    w('')
    w('function InitCustomPlayerSlots takes nothing returns nothing')
    w('')
    for idx, name, sx, sy, race in starts:
        w('    // Player %d (%s)' % (idx, name))
        w('    call SetPlayerStartLocation(Player(%d), %d)' % (idx, idx))
        w('    call SetPlayerColor(Player(%d), ConvertPlayerColor(%d))' % (idx, idx))
        w('    call SetPlayerRacePreference(Player(%d), %s)' % (idx, RACE_PREF[race]))
        w('    call SetPlayerRaceSelectable(Player(%d), true)' % idx)
        w('    call SetPlayerController(Player(%d), MAP_CONTROL_USER)' % idx)
        w('')
    w('endfunction')
    w('')
    w('function InitCustomTeams takes nothing returns nothing')
    w('    // Force: Force 1')
    for idx, *_ in starts:
        w('    call SetPlayerTeam(Player(%d), 0)' % idx)
    w('')
    w('endfunction')
    w('')
    w('function InitAllyPriorities takes nothing returns nothing')
    for idx, prio in sorted(info['ally_priorities'].items()):
        w('')
        w('    call SetStartLocPrioCount(%d, %d)' % (idx, len(prio)))
        for k, other in enumerate(prio):
            w('    call SetStartLocPrio(%d, %d, %d, MAP_LOC_PRIO_LOW)' % (idx, k, other))
    w('endfunction')
    w('')
    left, bottom, right, top = playable_bounds()
    w('//===========================================================================')
    w('function main takes nothing returns nothing')
    w('    call SetCameraBounds(%s + GetCameraMargin(CAMERA_MARGIN_LEFT), %s + GetCameraMargin(CAMERA_MARGIN_BOTTOM), '
      '%s - GetCameraMargin(CAMERA_MARGIN_RIGHT), %s - GetCameraMargin(CAMERA_MARGIN_TOP), '
      '%s + GetCameraMargin(CAMERA_MARGIN_LEFT), %s - GetCameraMargin(CAMERA_MARGIN_TOP), '
      '%s - GetCameraMargin(CAMERA_MARGIN_RIGHT), %s + GetCameraMargin(CAMERA_MARGIN_BOTTOM))'
      % (r(left), r(bottom), r(right), r(top), r(left), r(top), r(right), r(bottom)))
    w('    call SetDayNightModels("Environment\\\\DNC\\\\DNCLordaeron\\\\DNCLordaeronTerrain\\\\DNCLordaeronTerrain.mdl", '
      '"Environment\\\\DNC\\\\DNCLordaeron\\\\DNCLordaeronUnit\\\\DNCLordaeronUnit.mdl")')
    w('    call NewSoundEnvironment("Default")')
    w('    call SetAmbientDaySound("LordaeronSummerDay")')
    w('    call SetAmbientNightSound("LordaeronSummerNight")')
    w('    call SetMapMusic("Music", true, 0)')
    w('    call CreateRegions()')
    w('    call CreateAllUnits()')
    w('    call InitBlizzard()')
    w('    call InitGlobals()')
    w('    call InitCustomTriggers()')
    w('endfunction')
    w('')
    w('//===========================================================================')
    w('function config takes nothing returns nothing')
    w('    call SetMapName(%s)' % jstr(info['name']))
    w('    call SetMapDescription(%s)' % jstr(info['description']))
    w('    call SetPlayers(%d)' % len(starts))
    w('    call SetTeams(%d)' % len(starts))
    w('    call SetGamePlacement(MAP_PLACEMENT_TEAMS_TOGETHER)')
    w('')
    for idx, name, sx, sy, race in starts:
        x = LEFT + sx * 128.0
        y = BOTTOM + sy * 128.0
        w('    call DefineStartLocation(%d, %s, %s)' % (idx, r(x), r(y)))
    w('')
    w('    // Player setup')
    w('    call InitCustomPlayerSlots()')
    for idx, *_ in starts:
        w('    call SetPlayerSlotAvailable(Player(%d), MAP_CONTROL_USER)' % idx)
    w('    call InitGenericPlayerSlots()')
    w('    call InitAllyPriorities()')
    w('endfunction')
    w('')
    return '\r\n'.join(L).replace('\n', '\r\n').replace('\r\r\n', '\r\n').encode('utf-8')


def ally_priorities(starts, count=2):
    out = {}
    for idx, name, sx, sy, race in starts:
        others = sorted((math.hypot(sx - ox, sy - oy), oidx) for oidx, _, ox, oy, _ in starts if oidx != idx)
        out[idx] = [o for _, o in others[:count]]
    return out
